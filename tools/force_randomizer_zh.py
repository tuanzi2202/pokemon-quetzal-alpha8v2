def find_ptrs(rom: bytes, offset: int) -> list[int]:
    out: list[int] = []
    candidates = {0x08000000 + offset}
    if offset >= 0x01000000:
        candidates.add(0x09000000 + (offset & 0x00FFFFFF))
    for ptr in candidates:
        if not (0x08000000 <= ptr <= 0x09FFFFFF):
            continue
        needle = struct.pack("<I", ptr)
        idx = 0
        while True:
            i = rom.find(needle, idx)
            if i < 0:
                break
            if i % 4 == 0:
                out.append(i)
            idx = i + 1
            if len(out) > 40:
                break
    return sorted(set(out))


def encode_zh(zh: str, golden: bytes, off: int) -> bytes | None:
    if "{FD:" in zh:
        body, missing = encode_text_safe(zh.split("{FD:")[0])
        if missing:
            return None
        raw = golden[off : off + 16]
        fd_at = raw.find(b"\xfd")
        if fd_at < 0:
            return body[:-1] + bytes([0x00, 0xFD, 0x03, 0xFF])
        # include through FF
        end = raw.find(b"\xff", fd_at)
        return body[:-1] + raw[fd_at : end + 1]
    enc, missing = encode_text_safe(zh)
    if missing:
        print("missing", hex(off), zh, missing)
        return None
    return enc


def main() -> int:
    golden = GOLDEN.read_bytes()
    data = bytearray(ROM.read_bytes())
    cursor_path = ROOT / "work" / "free_cursor.txt"
    free_at = int(cursor_path.read_text().strip(), 0) if cursor_path.exists() else FREE_START
    stats = {"patched": 0, "no_ptr": 0, "fail": 0}
    seen: set[int] = set()

    for off, zh in FORCED:
        if off in seen:
            continue
        enc = encode_zh(zh, golden, off)
        if enc is None:
            stats["fail"] += 1
            continue
        ptrs = [
            p
            for p in find_ptrs(golden, off)
            if 0x08000000 <= struct.unpack_from("<I", data, p)[0] <= 0x09FFFFFF
        ]
        if not ptrs:
            stats["no_ptr"] += 1
            continue
        if free_at + len(enc) > FREE_END:
            print("FREE EXHAUSTED at", hex(off))
            break
        new_off = free_at
        data[new_off : new_off + len(enc)] = enc
        free_at += (len(enc) + 3) & ~3
        new_ptr = struct.pack("<I", 0x08000000 + new_off)
        for p in ptrs:
            data[p : p + 4] = new_ptr
        seen.add(off)
        stats["patched"] += 1

    ROM.write_bytes(data)
    # keep out/ in sync (hot-swap / release source)
    out = ROOT / "out" / "quetzal_084_cn.gba"
    out.write_bytes(data)
    cursor_path.write_text(hex(free_at), encoding="utf-8")
    print(json.dumps(stats, ensure_ascii=False))
    return 0


